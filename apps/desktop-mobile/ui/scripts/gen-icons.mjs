// Writes src/components/icons.ts from the Lucide icons (ISC licence) the app names.
// Run: node scripts/gen-icons.mjs   (needs the lucide-static dev dependency)
import { readFileSync, writeFileSync } from 'node:fs';
const MAP = {
  photos: 'image', albums: 'images', search: 'search', settings: 'settings', backup: 'cloud-upload',
  devices: 'monitor-smartphone', people: 'users', person: 'user', info: 'info', more: 'ellipsis', add: 'plus',
  check: 'check', warning: 'triangle-alert', folder: 'folder', lock: 'lock', close: 'x', share: 'share',
  heart: 'heart', keep: 'hard-drive', addalbum: 'image-plus', unalbum: 'image-minus', trash: 'trash-2',
  play: 'play', live: 'aperture', shield: 'shield-check', key: 'key-round', pause: 'pause', cloud: 'cloud',
  pin: 'pin', place: 'map-pin', camera: 'camera', clock: 'clock', calendar: 'calendar', thing: 'box',
  block: 'ban', print: 'printer', download: 'download', chevron: 'chevron-right', back: 'chevron-left',
  sync: 'refresh-cw', edit: 'pencil', link: 'link', star: 'star', face: 'smile',
};
let out = `// Generated by scripts/gen-icons.mjs from Lucide (https://lucide.dev, ISC licence,\n// Copyright (c) Lucide Contributors; portions Copyright (c) Cole Bemis 2013-2022 as part of Feather, MIT).\n// Do not edit by hand.\nexport const ICONS = {\n`;
for (const [name, file] of Object.entries(MAP)) {
  const svg = readFileSync(`node_modules/lucide-static/icons/${file}.svg`, 'utf8');
  const inner = svg.replace(/^[\s\S]*?viewBox="0 0 24 24"[\s\S]*?>\s*/, '').replace(/<\/svg>\s*$/, '').replace(/\s*\n\s*/g, ' ').trim();
  out += `  ${name}: ${JSON.stringify(inner)},\n`;
}
out += '} as const;\n';
writeFileSync('src/components/icons.ts', out);
